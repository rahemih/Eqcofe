import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir=dirname(fileURLToPath(import.meta.url));
const repoRoot=resolve(scriptDir,"../../..");
const shellPath=resolve(repoRoot,"docs/13-product-design/step56-admin-shell-wireframes.json");
const operationPath=resolve(repoRoot,"docs/13-product-design/step56-final-audit/operation-matrix.json");
const outputPath=resolve(repoRoot,"apps/admin/app/navigation/destinations.generated.ts");
const shell=JSON.parse(readFileSync(shellPath,"utf8"));
const operations=JSON.parse(readFileSync(operationPath,"utf8"));
const excluded=new Set(["AD-B-01","AD-B-03","AD-B-04","AD-B-05","AD-B-06","AD-B-07"]);
const bySurface=new Map();
const destinationById=new Map(shell.destinations.map((item)=>[item.surface,item]));

for(const operation of operations){
  if(operation.blocked===true)continue;
  if(Array.isArray(operation.gapIds)&&operation.gapIds.length>0)continue;
  if(typeof operation.executionAuthority==="string"&&operation.executionAuthority.startsWith("NO_ACTION"))continue;
  const runtime=operation.permissionClaims?.runtime;
  if(!Array.isArray(runtime))continue;
  const destination=destinationById.get(operation.owner);
  if(!destination||excluded.has(destination.surface))continue;
  const permissions=[...new Set(runtime.map((value)=>String(value).trim()).filter(Boolean))].sort();
  const entry=bySurface.get(destination.surface)??{
    surface:destination.surface,
    label:destination.label,
    group:destination.group,
    alternatives:new Map(),
  };
  entry.alternatives.set(JSON.stringify(permissions),permissions);
  bySurface.set(destination.surface,entry);
}

const groups=shell.adminNavigation.map((group)=>({id:group.id,label:group.label}));
const destinations=shell.destinations
  .filter((destination)=>bySurface.has(destination.surface))
  .map((destination)=>{
    const entry=bySurface.get(destination.surface);
    return {
      surface:entry.surface,
      label:entry.label,
      group:entry.group,
      permissionAlternatives:[...entry.alternatives.values()],
    };
  });

if(destinations.length!==62)throw new Error(`STEP67_E_DESTINATION_COUNT_DRIFT:${destinations.length}`);
const payload=`// GENERATED by apps/admin/scripts/generate-step67-destinations.mjs
// Sources: step56-admin-shell-wireframes.json + step56-final-audit/operation-matrix.json
export const ADMIN_NAV_GROUPS = ${JSON.stringify(groups,null,2)} as const;

export const ADMIN_DESTINATIONS = ${JSON.stringify(destinations,null,2)} as const;

export type AdminNavGroupId = (typeof ADMIN_NAV_GROUPS)[number]["id"];
export type AdminDestination = (typeof ADMIN_DESTINATIONS)[number];
`;

if(process.argv.includes("--check")){
  const current=readFileSync(outputPath,"utf8");
  if(current!==payload)throw new Error("STEP67_E_DESTINATION_REGISTRY_DRIFT");
  console.log(JSON.stringify({status:"PASS",stage:"67-E",destinations:destinations.length,groups:groups.length,source:"repository-proven operation evidence"},null,2));
}else{
  writeFileSync(outputPath,payload);
}
